  player_name VARCHAR(150) NOT NULL,
  team_name VARCHAR(100) NOT NULL,
  team_id INT UNSIGNED NOT NULL,
  pos ENUM('GKP','DEF','MID','FOR') NOT NULL,
  web_name VARCHAR(100) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'Available',
  news TEXT NULL,
  price DECIMAL(5,1) NOT NULL DEFAULT 0.0,
  points INT NOT NULL DEFAULT 0,
  form DECIMAL(6,2) NOT NULL DEFAULT 0,
  minutes INT NOT NULL DEFAULT 0,
  goals INT NOT NULL DEFAULT 0,
  assists INT NOT NULL DEFAULT 0,
  cs INT NOT NULL DEFAULT 0,
  saves INT NOT NULL DEFAULT 0,
  yc INT NOT NULL DEFAULT 0,
  rc INT NOT NULL DEFAULT 0,
  tout INT NOT NULL DEFAULT 0,
  tout_event INT NOT NULL DEFAULT 0,
  tin INT NOT NULL DEFAULT 0,
  tin_event INT NOT NULL DEFAULT 0,
  selected_by_percent DECIMAL(6,2) NOT NULL DEFAULT 0,
  cost_change_event INT NOT NULL DEFAULT 0,
  cost_change_event_fall INT NOT NULL DEFAULT 0,
  cost_change_start INT NOT NULL DEFAULT 0,
  cost_change_start_fall INT NOT NULL DEFAULT 0,
  dreamteam_count INT NOT NULL DEFAULT 0,
  ppg DECIMAL(6,2) NOT NULL DEFAULT 0,
  value_form DECIMAL(8,2) NOT NULL DEFAULT 0,
  value_season DECIMAL(8,2) NOT NULL DEFAULT 0,
  influence DECIMAL(8,2) NOT NULL DEFAULT 0,
  creativity DECIMAL(8,2) NOT NULL DEFAULT 0,
  threat DECIMAL(8,2) NOT NULL DEFAULT 0,
  ict_index DECIMAL(8,2) NOT NULL DEFAULT 0,
  influence_rank INT NULL,
  influence_rank_type INT NULL,
  creativity_rank INT NULL,
  creativity_rank_type INT NULL,
  threat_rank INT NULL,
  threat_rank_type INT NULL,
  ict_index_rank INT NULL,
  ict_index_rank_type INT NULL,
