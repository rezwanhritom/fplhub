  KEY idx_player_team (team_id),
  KEY idx_player_pos (pos),
  KEY idx_player_web_name (web_name),
  CONSTRAINT fk_player_team FOREIGN KEY (team_id) REFERENCES fpl_hub_team_data (team_id)
    ON UPDATE CASCADE ON DELETE RESTRICT
